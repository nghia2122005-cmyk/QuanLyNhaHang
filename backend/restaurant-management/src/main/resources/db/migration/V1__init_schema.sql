CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('OWNER', 'MANAGER', 'CASHIER', 'WAITER', 'KITCHEN_STAFF', 'HEAD_CHEF')),
    status VARCHAR(30) NOT NULL CHECK (status IN ('ACTIVE', 'LOCKED'))
);

CREATE TABLE dining_area (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE dining_table (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT NOT NULL REFERENCES dining_area(id) ON DELETE RESTRICT,
    name VARCHAR(50) NOT NULL,
    capacity INT NOT NULL CHECK (capacity > 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'INACTIVE'))
);

CREATE TABLE reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id BIGINT NOT NULL REFERENCES dining_table(id) ON DELETE RESTRICT,
    created_by_id BIGINT NOT NULL REFERENCES account(id) ON DELETE RESTRICT,
    customer_name VARCHAR(100) NOT NULL,
    customer_phone VARCHAR(15) NOT NULL,
    guest_count INT NOT NULL CHECK (guest_count > 0),
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    note VARCHAR(500),
    status VARCHAR(30) NOT NULL CHECK (status IN ('CONFIRMED', 'SEATED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_reservation_time CHECK (start_time < end_time)
);

CREATE TABLE service_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id BIGINT NOT NULL REFERENCES dining_table(id) ON DELETE RESTRICT,
    reservation_id BIGINT REFERENCES reservation(id) ON DELETE RESTRICT,
    created_by_id BIGINT NOT NULL REFERENCES account(id) ON DELETE RESTRICT,
    opened_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    status VARCHAR(30) NOT NULL CHECK (status IN ('ACTIVE', 'CLOSED'))
);
CREATE UNIQUE INDEX uq_active_session_table ON service_session(table_id) WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX uq_session_reservation ON service_session(reservation_id) WHERE reservation_id IS NOT NULL;

CREATE TABLE menu_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    price NUMERIC(14,0) NOT NULL CHECK (price >= 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('ON_SALE', 'DISCONTINUED'))
);

CREATE TABLE ingredient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    unit VARCHAR(20) NOT NULL,
    min_stock NUMERIC(12,3) NOT NULL CHECK (min_stock >= 0),
    track_lot BOOLEAN NOT NULL,
    track_expiry BOOLEAN NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE recipe_item (
    menu_item_id BIGINT NOT NULL REFERENCES menu_item(id) ON DELETE RESTRICT,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id) ON DELETE RESTRICT,
    quantity_per_serving NUMERIC(12,3) NOT NULL CHECK (quantity_per_serving > 0),
    PRIMARY KEY (menu_item_id, ingredient_id)
);

CREATE TABLE food_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES service_session(id) ON DELETE RESTRICT,
    created_by_id BIGINT NOT NULL REFERENCES account(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES food_order(id) ON DELETE RESTRICT,
    menu_item_id BIGINT NOT NULL REFERENCES menu_item(id) ON DELETE RESTRICT,
    quantity INT NOT NULL CHECK (quantity > 0),
    note VARCHAR(500),
    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING', 'COOKING', 'READY', 'SERVED', 'UNAVAILABLE', 'CANCELLED')),
    unavailable_reason VARCHAR(500),
    unit_price_at_order NUMERIC(14,0) NOT NULL CHECK (unit_price_at_order >= 0),
    CONSTRAINT ck_order_item_unavailable_reason CHECK (status <> 'UNAVAILABLE' OR unavailable_reason IS NOT NULL)
);

CREATE TABLE ingredient_lot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id) ON DELETE RESTRICT,
    lot_number VARCHAR(50),
    expiry_date DATE
);

CREATE TABLE stock_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by_id BIGINT NOT NULL REFERENCES account(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE stock_receipt_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL REFERENCES stock_receipt(id) ON DELETE RESTRICT,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id) ON DELETE RESTRICT,
    lot_id BIGINT REFERENCES ingredient_lot(id) ON DELETE RESTRICT,
    quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0)
);

CREATE TABLE stocktake (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by_id BIGINT NOT NULL REFERENCES account(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE stocktake_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_id BIGINT NOT NULL REFERENCES stocktake(id) ON DELETE RESTRICT,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id) ON DELETE RESTRICT,
    lot_id BIGINT REFERENCES ingredient_lot(id) ON DELETE RESTRICT,
    system_quantity NUMERIC(12,3) NOT NULL,
    actual_quantity NUMERIC(12,3) NOT NULL CHECK (actual_quantity >= 0),
    note VARCHAR(500)
);

CREATE TABLE stock_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id) ON DELETE RESTRICT,
    lot_id BIGINT REFERENCES ingredient_lot(id) ON DELETE RESTRICT,
    receipt_item_id BIGINT REFERENCES stock_receipt_item(id) ON DELETE RESTRICT,
    order_item_id BIGINT REFERENCES order_item(id) ON DELETE RESTRICT,
    stocktake_item_id BIGINT REFERENCES stocktake_item(id) ON DELETE RESTRICT,
    performed_by_id BIGINT NOT NULL REFERENCES account(id) ON DELETE RESTRICT,
    movement_type VARCHAR(30) NOT NULL CHECK (movement_type IN ('RECEIPT', 'CONSUMPTION', 'STOCKTAKE_ADJUSTMENT', 'DISPOSAL')),
    quantity_change NUMERIC(12,3) NOT NULL CHECK (quantity_change <> 0),
    reason VARCHAR(500),
    occurred_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_stock_movement_source_sign CHECK (
        (movement_type = 'RECEIPT' AND quantity_change > 0 AND receipt_item_id IS NOT NULL) OR
        (movement_type = 'CONSUMPTION' AND quantity_change < 0 AND order_item_id IS NOT NULL) OR
        (movement_type = 'STOCKTAKE_ADJUSTMENT' AND stocktake_item_id IS NOT NULL) OR
        (movement_type = 'DISPOSAL' AND quantity_change < 0 AND reason IS NOT NULL)
    )
);
CREATE UNIQUE INDEX uq_movement_receipt_item ON stock_movement(receipt_item_id) WHERE receipt_item_id IS NOT NULL;
CREATE UNIQUE INDEX uq_movement_stocktake_item ON stock_movement(stocktake_item_id) WHERE stocktake_item_id IS NOT NULL;
CREATE UNIQUE INDEX uq_consumption_order_ingredient ON stock_movement(order_item_id, ingredient_id) WHERE movement_type = 'CONSUMPTION';

CREATE TABLE invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL UNIQUE REFERENCES service_session(id) ON DELETE RESTRICT,
    cashier_id BIGINT NOT NULL REFERENCES account(id) ON DELETE RESTRICT,
    payment_method VARCHAR(30) NOT NULL CHECK (payment_method IN ('CASH', 'BANK_TRANSFER')),
    amount NUMERIC(14,0) NOT NULL CHECK (amount >= 0),
    paid_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE revenue_reconciliation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cashier_id BIGINT NOT NULL REFERENCES account(id) ON DELETE RESTRICT,
    manager_id BIGINT REFERENCES account(id) ON DELETE RESTRICT,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    system_revenue NUMERIC(14,0) NOT NULL,
    actual_amount NUMERIC(14,0) NOT NULL CHECK (actual_amount >= 0),
    difference_reason VARCHAR(500),
    reconciled_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_reconciliation_time CHECK (start_time < end_time)
);

CREATE INDEX idx_reservation_table_time_status ON reservation(table_id, start_time, end_time, status);
CREATE INDEX idx_session_table_status ON service_session(table_id, status);
CREATE INDEX idx_food_order_session_created ON food_order(session_id, created_at);
CREATE INDEX idx_order_item_order_status ON order_item(order_id, status);
CREATE INDEX idx_order_item_status ON order_item(status);
CREATE INDEX idx_movement_ingredient_time ON stock_movement(ingredient_id, occurred_at);
CREATE INDEX idx_lot_expiry ON ingredient_lot(expiry_date);
CREATE INDEX idx_invoice_paid ON invoice(paid_at);
CREATE INDEX idx_reconciliation_time ON revenue_reconciliation(start_time, end_time);
CREATE INDEX idx_dining_table_area ON dining_table(area_id);
CREATE INDEX idx_lot_ingredient ON ingredient_lot(ingredient_id);
CREATE INDEX idx_recipe_ingredient ON recipe_item(ingredient_id);
CREATE INDEX idx_receipt_item_receipt ON stock_receipt_item(receipt_id);
CREATE INDEX idx_stocktake_item_stocktake ON stocktake_item(stocktake_id);
